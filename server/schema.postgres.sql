CREATE TABLE IF NOT EXISTS stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT NOT NULL DEFAULT '',
  location_name TEXT NOT NULL DEFAULT '',
  maps_url TEXT NOT NULL DEFAULT '',
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('superadmin','store_manager','customer','rider')),
  store_id BIGINT REFERENCES stores(id) ON DELETE SET NULL,
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  is_online SMALLINT NOT NULL DEFAULT 0 CHECK (is_online IN (0,1)),
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT 'Meals',
  price DOUBLE PRECISION NOT NULL CHECK (price >= 0),
  old_price DOUBLE PRECISION CHECK (old_price IS NULL OR old_price >= 0),
  promo_price DOUBLE PRECISION CHECK (promo_price IS NULL OR promo_price >= 0),
  promo_label TEXT NOT NULL DEFAULT '',
  promo_starts_at TEXT,
  promo_ends_at TEXT,
  is_promoted SMALLINT NOT NULL DEFAULT 0 CHECK (is_promoted IN (0,1)),
  image_url TEXT NOT NULL DEFAULT '/images/hero-food.png',
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  is_available SMALLINT NOT NULL DEFAULT 1 CHECK (is_available IN (0,1)),
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS product_images (
  id UUID PRIMARY KEY,
  mime_type TEXT NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','image/webp','image/avif')),
  file_name TEXT NOT NULL DEFAULT 'product-image',
  image_data BYTEA NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
  id TEXT PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES users(id),
  store_id BIGINT NOT NULL REFERENCES stores(id),
  rider_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  status TEXT NOT NULL CHECK (status IN ('Pending','Confirmed','Preparing','Ready for Pickup','Out for Delivery','Delivered','Cancelled')),
  subtotal DOUBLE PRECISION NOT NULL CHECK (subtotal >= 0),
  delivery_fee DOUBLE PRECISION NOT NULL CHECK (delivery_fee >= 0),
  total DOUBLE PRECISION NOT NULL CHECK (total >= 0),
  discount_total DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
  student_discount DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (student_discount >= 0),
  group_discount DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (group_discount >= 0),
  group_order_id TEXT,
  payment_method TEXT NOT NULL DEFAULT 'Cash on delivery',
  delivery_address TEXT NOT NULL,
  order_notes TEXT NOT NULL DEFAULT '',
  eta_minutes INTEGER CHECK (eta_minutes IS NULL OR eta_minutes BETWEEN 0 AND 240),
  eta_at TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id TEXT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  unit_price DOUBLE PRECISION NOT NULL CHECK (unit_price >= 0),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  line_total DOUBLE PRECISION NOT NULL CHECK (line_total >= 0),
  ordered_by_customer_id BIGINT REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS tracking_updates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id TEXT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  status TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  location_label TEXT NOT NULL DEFAULT '',
  eta_at TEXT,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS ratings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  customer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  order_id TEXT REFERENCES orders(id) ON DELETE SET NULL,
  reviewer_name TEXT NOT NULL,
  score INTEGER NOT NULL CHECK (score BETWEEN 1 AND 5),
  review TEXT NOT NULL DEFAULT '',
  is_visible SMALLINT NOT NULL DEFAULT 1 CHECK (is_visible IN (0,1)),
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_ratings_order_customer ON ratings(order_id, customer_id) WHERE order_id IS NOT NULL AND customer_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_products_store ON products(store_id);
CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders(customer_id);
CREATE INDEX IF NOT EXISTS idx_orders_store ON orders(store_id);
CREATE INDEX IF NOT EXISTS idx_tracking_order ON tracking_updates(order_id, created_at);
CREATE TABLE IF NOT EXISTS app_settings (
  setting_key TEXT PRIMARY KEY,
  setting_value TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS group_orders (
  id TEXT PRIMARY KEY,
  join_code TEXT NOT NULL UNIQUE,
  host_customer_id BIGINT NOT NULL REFERENCES users(id),
  store_id BIGINT NOT NULL REFERENCES stores(id),
  delivery_address TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED','CANCELLED')),
  order_id TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS group_order_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_order_id TEXT NOT NULL REFERENCES group_orders(id) ON DELETE CASCADE,
  customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  joined_at TEXT NOT NULL,
  UNIQUE (group_order_id, customer_id)
);
CREATE TABLE IF NOT EXISTS group_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_order_id TEXT NOT NULL REFERENCES group_orders(id) ON DELETE CASCADE,
  customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  unit_price DOUBLE PRECISION NOT NULL CHECK (unit_price >= 0),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_group_order_members_customer ON group_order_members(customer_id);
CREATE INDEX IF NOT EXISTS idx_group_order_items_group ON group_order_items(group_order_id);
CREATE TABLE IF NOT EXISTS rider_job_declines (
  rider_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  order_id TEXT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  PRIMARY KEY (rider_id, order_id)
);
